    from_square = fields.CharField(max_length=2)
    to_square = fields.CharField(max_length=2)
    captured_squares = fields.JSONField(default=list)
    became_king = fields.BooleanField(default=False)
    board_after = fields.JSONField()
    created_at = fields.DatetimeField(auto_now_add=True)
